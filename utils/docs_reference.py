"""
docs_reference.py — Command line and configuration reference of the documentation.

``docs/reference/cli.md`` and ``docs/reference/configuration.md`` each hold a part
between the two ``GENERATED`` markers that is written from the code, so the
reference cannot drift from it:

* command line: the parser of every tool (``build_parser`` in each script), with
  its options, defaults and help texts in the order of the parser;
* configuration: every TOML key of ``train.config.TOML_KEYS`` with the default and
  the description (``setting(..., doc)``) of its ``TrainingConfig`` field and the
  allowed values (``CHOICES``); every key of ``export_config.EXPORT_CONFIG_KEYS`` and
  ``rollout.ROLLOUT_CONFIG_KEYS`` with the default and the help text of its option.

The text around the markers is written by hand. Defaults that are paths inside the
repository are shown relative to it.

Usage
-----
    python utils/docs_reference.py        # rewrite the generated parts
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

_REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO_ROOT))   # packages: dataset_preprocessor, models, train, ...

START = "<!-- GENERATED by utils/docs_reference.py from the code: edit there, not here -->"
END = "<!-- GENERATED end -->"
CLI_PAGE = _REPO_ROOT / "docs" / "reference" / "cli.md"
CONFIG_PAGE = _REPO_ROOT / "docs" / "reference" / "configuration.md"

# (heading, command, module): every command line tool, in the order of the workflow.
COMMANDS = [
    ("export", "python -m dataset_preprocessor.export", "dataset_preprocessor.export"),
    ("tfrecord_to_d3plot", "python -m dataset_preprocessor.tfrecord_to_d3plot",
     "dataset_preprocessor.tfrecord_to_d3plot"),
    ("tfrecord_to_vtk", "python -m dataset_preprocessor.tfrecord_to_vtk",
     "dataset_preprocessor.tfrecord_to_vtk"),
    ("remesh_pole", "python utils/remesh_pole.py", "utils.remesh_pole"),
    ("train", "python train/train.py", "train.train"),
    ("rollout", "python predict/rollout.py", "predict.rollout"),
    ("plot_losses", "python utils/plot_losses.py", "utils.plot_losses"),
    ("evaluate_run", "python utils/evaluate_run.py", "utils.evaluate_run"),
    ("compare_paper", "python utils/compare_paper.py", "utils.compare_paper"),
    ("check_protocol", "python utils/check_protocol.py", "utils.check_protocol"),
    ("explore_data", "python utils/explore_data.py", "utils.explore_data"),
    ("animate_rollout", "python utils/animate_rollout.py", "utils.animate_rollout"),
    ("app", "python utils/app.py", "utils.app"),
]


def _text(value: str) -> str:
    """Text for a Markdown table cell; code spans (`...`) stay as they are."""
    parts = value.split("`")
    for i in range(0, len(parts), 2):
        for old, new in (("|", "\\|"), ("<", "&lt;"), (">", "&gt;"), ("*", "\\*")):
            parts[i] = parts[i].replace(old, new)
    return " ".join("`".join(parts).split())


def _relative(value: Any) -> Any:
    """Paths inside the repository relative to it, with / as on the website (also on Windows)."""
    if isinstance(value, (str, Path)) and str(value).startswith(str(_REPO_ROOT)):
        return Path(value).relative_to(_REPO_ROOT).as_posix()
    return value


def _cli_default(action: argparse.Action) -> str:
    default = _relative(action.default)
    if default is None or default == argparse.SUPPRESS or default == []:
        return "–"
    if isinstance(action, argparse.BooleanOptionalAction):
        return f"`{action.option_strings[0 if default else 1]}`"
    if isinstance(default, (list, tuple)):
        default = " ".join(map(str, default))
    return f"`{default}`"


def _cli_help(action: argparse.Action, parser: argparse.ArgumentParser) -> str:
    if not action.help:
        raise ValueError(f"{parser.prog}: {action.option_strings or action.dest} has no help")
    params = {**vars(action), "prog": parser.prog, "default": _relative(action.default)}
    text = action.help % params
    return _text(text[0].upper() + text[1:])


def command_section(heading: str, command: str, module: str) -> List[str]:
    """Markdown of one command line tool."""
    parser = importlib.import_module(module).build_parser()
    parser.prog = command
    formatter = parser._get_formatter()
    positionals = [a for a in parser._actions if not a.option_strings]
    usage = " ".join([command, *(formatter._format_args(a, a.dest) for a in positionals),
                      "[options]"])
    lines = [f"## {heading}", "", _text(parser.description or ""), "", "```bash", usage,
             "```", ""]
    for group in parser._action_groups:
        actions = [a for a in group._group_actions if not isinstance(a, argparse._HelpAction)]
        if not actions:
            continue
        if group.title not in ("positional arguments", "options", "optional arguments"):
            lines += [f"**{_text(group.title)}**", ""]
        first = "Argument" if not actions[0].option_strings else "Option"
        lines += [f"| {first} | Default | Description |", "|---|---|---|"]
        for action in actions:
            name = _text(formatter._format_action_invocation(action))
            lines.append(f"| `{name}` | {_cli_default(action)} | {_cli_help(action, parser)} |")
        lines.append("")
    return lines


def _toml_value(value: Any) -> str:
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, str):
        return f'`"{value}"`'
    if isinstance(value, int) and value >= 10_000:
        return f"`{value:_}`"
    if isinstance(value, (list, tuple)):
        return "`[" + ", ".join(f'"{v}"' for v in value) + "]`"
    return f"`{value}`"


def config_sections() -> List[str]:
    """Markdown tables of every TOML section, in the order of ``TOML_KEYS``."""
    from train.config import CHOICES, TOML_KEYS, TrainingConfig
    from train.early_stopping import CRITERIA

    choices = {**CHOICES, "early_stopping_criteria": CRITERIA}
    fields = {f.name: f for f in dataclasses.fields(TrainingConfig)}
    sections: Dict[str, List[Tuple[str, str]]] = {}
    for key, name in TOML_KEYS.items():
        section, _, short = key.rpartition(".")
        sections.setdefault(section, []).append((short, name))
    lines: List[str] = []
    for section, keys in sections.items():
        lines += [f"## [{section}]", "", "| Key | Default | Description |", "|---|---|---|"]
        for short, name in keys:
            field = fields[name]
            doc = field.metadata.get("doc")
            if not doc:
                raise ValueError(f"TrainingConfig.{name} has no description (setting(..., doc))")
            default = (field.default_factory() if field.default is dataclasses.MISSING
                       else field.default)
            text = doc[0].upper() + doc[1:]
            named = [f"`{c}`" for c in choices.get(name, ())]
            if named and not all(c in doc for c in named):   # unless the text names them all
                text += ("; any of " if isinstance(default, list) else "; one of ") + ", ".join(named)
            shared = [k.rpartition(".")[0] for k, n in TOML_KEYS.items()
                      if n == name and not k.startswith(section + ".")]
            if shared:
                text += "; one setting with " + ", ".join(f"`[{s}]`" for s in shared)
            lines.append(f"| `{short}` | {_toml_value(default)} | {_text(text)} |")
        lines.append("")
    return lines


def _option_tables(heading: str, command: str, config_keys: Dict[str, str],
                   parser: argparse.ArgumentParser) -> List[str]:
    """Markdown tables of the TOML sections of a config whose keys stand for options."""
    actions = {action.dest: action for action in parser._actions}
    sections: Dict[str, List[Tuple[str, str]]] = {}
    for key, dest in config_keys.items():
        section, _, short = key.rpartition(".")
        sections.setdefault(section, []).append((short, dest))
    lines = [f"## {heading}", "",
             f"The keys of `{command} --config FILE`, each with the default and the description "
             "of its command line option.", ""]
    for section, keys in sections.items():
        lines += [f"### [{section}]", "", "| Key | Default | Description |", "|---|---|---|"]
        for short, dest in keys:
            action = actions[dest]
            lines.append(f"| `{short}` | {_cli_default(action)} | {_cli_help(action, parser)} |")
        lines.append("")
    return lines


def export_config_sections() -> List[str]:
    """The reference of an export config."""
    from dataset_preprocessor.export import build_parser
    from dataset_preprocessor.export_config import COMPONENTS_SECTION, EXPORT_CONFIG_KEYS

    parser = build_parser()
    components = next(action for action in parser._actions if action.dest == COMPONENTS_SECTION)
    return (_option_tables("Export config", "python -m dataset_preprocessor.export",
                           EXPORT_CONFIG_KEYS, parser)
            + [f"### [{COMPONENTS_SECTION}]", "", _cli_help(components, parser), ""])


def rollout_config_sections() -> List[str]:
    """The reference of a rollout config."""
    from predict.rollout import ROLLOUT_CONFIG_KEYS, build_parser

    return _option_tables("Rollout config", "python predict/rollout.py", ROLLOUT_CONFIG_KEYS,
                          build_parser())


def _replace_generated(page: Path, lines: List[str]) -> str:
    text = page.read_text(encoding="utf-8")
    head, start, rest = text.partition(START)
    _, end, tail = rest.partition(END)
    if not start or not end:
        raise ValueError(f"{page}: markers {START!r} and {END!r} not found")
    return head + START + "\n\n" + "\n".join(lines).rstrip() + "\n\n" + END + tail


def pages() -> Dict[Path, str]:
    """Generated text of both reference pages."""
    cli = [line for section in COMMANDS for line in command_section(*section)]
    return {CLI_PAGE: _replace_generated(CLI_PAGE, cli),
            CONFIG_PAGE: _replace_generated(CONFIG_PAGE,
                                            config_sections() + export_config_sections()
                                            + rollout_config_sections())}


def main() -> None:
    for page, text in pages().items():
        if page.read_text(encoding="utf-8") != text:
            page.write_text(text, encoding="utf-8")
            print(f"updated {page.relative_to(_REPO_ROOT)}")
        else:
            print(f"current {page.relative_to(_REPO_ROOT)}")


if __name__ == "__main__":
    main()
